def obter_configuracao(recomendacao, armazenamento):

    processador = recomendacao["processador"]
    placa_video = recomendacao["placa_video"]
    ram = recomendacao["ram"]

    precos_processador = {
        "Processador de entrada": 650,
        "Processador intermediário": 950,
        "Processador de alto desempenho": 1800
    }

    precos_ram = {
        "8 GB": 180,
        "16 GB": 400,
        "32 GB": 750
    }

    precos_armazenamento = {
        "500gb": 280,
        "1tb": 550,
        "2tb": 950
    }

    precos_placa_mae = {
        "Processador de entrada": 400,
        "Processador intermediário": 600,
        "Processador de alto desempenho": 950
    }

    precos_fonte = {
        "Processador de entrada": 250,
        "Processador intermediário": 350,
        "Processador de alto desempenho": 500
    }

    precos_gabinete = {
        "Processador de entrada": 180,
        "Processador intermediário": 280,
        "Processador de alto desempenho": 400
    }

    texto_video = placa_video.lower()

    if "integrado" in texto_video or "integrada" in texto_video:
        preco_placa_video = 0

    elif "básica" in texto_video:
        preco_placa_video = 800

    elif "intermediária" in texto_video:
        preco_placa_video = 1500

    elif "alto desempenho" in texto_video:
        preco_placa_video = 2800

    elif "dedicada" in texto_video:
        preco_placa_video = 1800

    else:
        preco_placa_video = 0

    if preco_placa_video >= 2500:

        preco_fonte = 650

    elif preco_placa_video >= 1200:

        preco_fonte = 450

    else:

        preco_fonte = precos_fonte[processador]

    precos = {
        "Processador": precos_processador[processador],
        "Placa de vídeo": preco_placa_video,
        "Memória RAM": precos_ram[ram],
        "Armazenamento": precos_armazenamento[armazenamento],
        "Placa-mãe": precos_placa_mae[processador],
        "Fonte": preco_fonte,
        "Gabinete": precos_gabinete[processador]
    }

    return precos


