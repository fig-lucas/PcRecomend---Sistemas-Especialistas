def escolher(pergunta, opcoes):

    print("\n" + pergunta)

    for numero, opcao in enumerate(opcoes, 1):
        print(f"[{numero}] {opcao[0]}")

    while True:

        try:
            escolha = int(input("Escolha: "))

            if 1 <= escolha <= len(opcoes):
                return opcoes[escolha - 1][1]

        except ValueError:
            pass

        print("Opção inválida.")


ORCAMENTO_MINIMO = 2000


def obter_orcamento():

    while True:

        try:
            valor = float(
                input("\nDigite o orçamento total: R$ ")
            )

            if valor >= ORCAMENTO_MINIMO:
                return valor

            print(
                f"Orçamento insuficiente. O mínimo para montar "
                f"um computador é R$ {ORCAMENTO_MINIMO:.2f}."
            )
            continue

        except ValueError:
            pass

        print("Digite um valor válido.")


